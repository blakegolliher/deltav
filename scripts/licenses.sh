#!/usr/bin/env bash
# Dependency license gate for Delta-V. Compatible with bash 3.2 (macOS).
#
#   scripts/licenses.sh check    fail if any linked Go dependency, on any
#                                release platform, has a license outside
#                                the permitted list (or none at all)
#   scripts/licenses.sh report   check, then regenerate
#                                THIRD_PARTY_LICENSES.md and
#                                third_party/licenses/ (LICENSE + NOTICE copies)
#
# MODULE_DIR (default: repo root) selects the module to audit; OUT_DIR
# (default: repo root) is where report output goes.
set -euo pipefail

GO_LICENSES_VERSION=v2.0.1
PLATFORMS="linux/amd64 linux/arm64 darwin/arm64"
# Permitted by policy: Apache-2.0, MIT, BSD, ISC, MPL-2.0.
ALLOWED="Apache-2.0 MIT BSD-2-Clause BSD-3-Clause 0BSD ISC MPL-2.0"

ROOT=$(cd "$(dirname "$0")/.." && pwd)
MODULE_DIR=${MODULE_DIR:-$ROOT}
OUT_DIR=${OUT_DIR:-$ROOT}
CACHE=$ROOT/.cache
mode=${1:-check}

GO_LICENSES=$CACHE/bin/go-licenses
if [ ! -x "$GO_LICENSES" ]; then
	echo "installing go-licenses $GO_LICENSES_VERSION into $CACHE/bin" >&2
	(cd "$ROOT" && GOBIN=$CACHE/bin go install "github.com/google/go-licenses/v2@$GO_LICENSES_VERSION")
fi

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
# The template sees one row per (library, license); rows are merged below.
printf '{{range .}}{{.Name}}\t{{.Version}}\t{{.LicenseName}}\t{{.LicensePath}}\t{{.LicenseURL}}\n{{end}}' > "$tmp/tsv.tmpl"

own=$(cd "$MODULE_DIR" && go list -m)
# go-licenses must see the same GOROOT as the toolchain go.mod selects, or it
# misclassifies standard-library packages as module-less.
goroot=$(cd "$MODULE_DIR" && go env GOROOT)
for p in $PLATFORMS; do
	(cd "$MODULE_DIR" && GOROOT=$goroot GOOS=${p%/*} GOARCH=${p#*/} \
		"$GO_LICENSES" report ./... --ignore "$own" --template "$tmp/tsv.tmpl" 2>"$tmp/err") \
		>>"$tmp/all.tsv" || { cat "$tmp/err" >&2; echo "go-licenses failed for $p" >&2; exit 1; }
done
# Merge per-license rows into one row per library: licenses joined with " AND ".
sort -u "$tmp/all.tsv" | grep -v '^[[:space:]]*$' | awk -F'\t' -v OFS='\t' '
	{ k = $1 OFS $2; if (!(k in lic)) { order[++n] = k; path[k] = $4; url[k] = $5; lic[k] = $3 }
	  else if (index(" AND " lic[k] " AND ", " AND " $3 " AND ") == 0) lic[k] = lic[k] " AND " $3 }
	END { for (i = 1; i <= n; i++) { k = order[i]; print k, lic[k], path[k], url[k] } }' > "$tmp/libs.tsv" || true

bad=0
while IFS="$(printf '\t')" read -r name ver lic lpath url <&3; do
	# A library may carry several licenses ("A AND B"); each must be allowed.
	for l in $(echo "$lic" | sed 's/ AND / /g'); do
		case " $ALLOWED " in
		*" $l "*) ;;
		*) echo "NOT PERMITTED: $name $ver: $l" >&2; bad=1 ;;
		esac
	done
done 3< "$tmp/libs.tsv"
count=$(wc -l < "$tmp/libs.tsv" | tr -d ' ')
if [ "$bad" -ne 0 ]; then
	echo "license check FAILED ($count libraries)" >&2
	exit 1
fi
echo "license check passed: $count libraries, all in: $ALLOWED" >&2
[ "$mode" = report ] || exit 0

# first_copyright FILE...: the first concrete copyright line in the given
# files, e.g. "Copyright (c) 2020 Charmbracelet, Inc." Apache-2.0 boilerplate
# ("copyright notice that is ...", "[yyyy]") is not a holder and is skipped.
first_copyright() {
	[ $# -gt 0 ] || return 0
	cat "$@" </dev/null 2>/dev/null \
		| grep -iE '^[[:space:]]*(//[[:space:]]*)?copyright[[:space:]]+(\(c\)[[:space:]]*|©[[:space:]]*)?[0-9]{4}' \
		| grep -v '\[yyyy\]' | head -1 \
		| sed -e 's#^[[:space:]]*//[[:space:]]*##' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/|/\\|/g' || true
}

dest=$OUT_DIR/third_party/licenses
rm -rf "$dest"
mkdir -p "$dest"
md=$OUT_DIR/THIRD_PARTY_LICENSES.md
{
	echo "# Third-party licenses"
	echo
	echo "Generated by \`scripts/licenses.sh report\` from the Go module graph linked into"
	echo "\`deltav\` on $PLATFORMS. Do not edit by hand; edit the script and regenerate."
	echo "Permitted licenses: Apache-2.0, MIT, BSD (0BSD, 2- and 3-clause), ISC, MPL-2.0."
	echo
	echo "Each library's LICENSE, and NOTICE where upstream ships one, is copied verbatim"
	echo "under \`third_party/licenses/<library>/\`. No upstream file has been modified."
	echo
	echo "| Library | Version | License | Copyright (from upstream files) | NOTICE |"
	echo "|---|---|---|---|---|"
	while IFS="$(printf '\t')" read -r name ver lic lpath url <&3; do
		dir=$(dirname "$lpath")
		mkdir -p "$dest/$name"
		cp "$lpath" "$dest/$name/"
		notice=no
		for n in "$dir"/NOTICE*; do
			[ -f "$n" ] || continue
			cp "$n" "$dest/$name/"
			notice=yes
		done
		# Holder: LICENSE, then NOTICE, then the library's own source headers.
		c=$(first_copyright "$lpath")
		if [ -z "$c" ] && [ "$notice" = yes ]; then
			c=$(first_copyright "$dir"/NOTICE*)
		fi
		if [ -z "$c" ]; then
			c=$(first_copyright $(find "$dir" -maxdepth 3 -name '*.go' ! -name '*_test.go' </dev/null | sort | head -200))
			[ -z "$c" ] || c="$c (source headers)"
		fi
		[ -n "$c" ] || c="not stated in upstream files"
		printf '| [%s](%s) | %s | %s | %s | %s |\n' "$name" "$url" "${ver:--}" "$lic" "$c" "$notice"
	done 3< "$tmp/libs.tsv"
	echo
	echo "## Non-Go components"
	echo
	if [ -f "$ROOT/scripts/third_party_static.md" ]; then
		cat "$ROOT/scripts/third_party_static.md"
	else
		echo "None shipped yet."
	fi
} > "$md"
echo "wrote $md and $dest" >&2
